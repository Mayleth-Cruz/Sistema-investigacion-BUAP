/**
 * Mapeador universal de iconos para Categorías y Géneros
 * Convierte cualquier identificador o emoji histórico de BD en un SVG impecable.
 */
export function CategoryIcon({ nameOrEmoji = 'book', size = 18, color = 'currentColor', className = '' }) {
  const val = (nameOrEmoji || '').trim();

  // Mapeo por emoji histórico
  if (val === '🔬' || val === 'microscope') return <IconMicroscope size={size} color={color} className={className} />;
  if (val === '🌱' || val === 'leaf') return <IconLeaf size={size} color={color} className={className} />;
  if (val === '🩺' || val === 'health') return <IconStethoscope size={size} color={color} className={className} />;
  if (val === '🏛️' || val === '🏛' || val === 'landmark') return <IconLandmark size={size} color={color} className={className} />;
  if (val === '📊' || val === 'chart') return <IconChart size={size} color={color} className={className} />;
  if (val === '🎨' || val === 'palette') return <IconPalette size={size} color={color} className={className} />;
  if (val === '🎓' || val === 'graduation') return <IconGraduationCap size={size} color={color} className={className} />;
  if (val === '📄' || val === 'document') return <IconDocument size={size} color={color} className={className} />;
  if (val === '📖' || val === 'openbook') return <IconBook size={size} color={color} className={className} />;
  if (val === '📚' || val === 'books') return <IconBook size={size} color={color} className={className} />;
  if (val === '🎤' || val === 'microphone') return <IconMicrophone size={size} color={color} className={className} />;
  if (val === '⚙️' || val === '⚙' || val === 'settings') return <IconSettings size={size} color={color} className={className} />;
  if (val === '💡' || val === 'lightbulb') return <IconLightbulb size={size} color={color} className={className} />;
  if (val === '🧬' || val === 'dna') return <IconDna size={size} color={color} className={className} />;
  if (val === '💻' || val === 'laptop') return <IconLaptop size={size} color={color} className={className} />;

  // Por defecto, libro académico
  return <IconBook size={size} color={color} className={className} />;
}
